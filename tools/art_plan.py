if __name__ == "__main__":
    import json, pathlib
    root = pathlib.Path(__file__).resolve().parent.parent
    p = root / "data" / "scenes_ch01.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    jobs = {}
    for s in d["scenes"]:
        m = PLAN.get(s["id"], {})
        art = {}
        for idx, (name, prompt) in sorted(m.items()):
            full = "%s_%s" % (s["id"], name) if not name.startswith("ch01") else name
            # 同一张图可以被多场复用（比如行刑队），认第一次定义的名字
            art[str(idx)] = full
            if prompt:
                jobs[full] = prompt
        s["art"] = art
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")

    # 已存在的跳过
    have = {f.stem for f in (root / "art" / "scenes").glob("*.png")}
    todo = {k: v for k, v in jobs.items() if k not in have}
    out = root / "tools" / "art_jobs.tsv"
    with out.open("w", encoding="utf-8") as f:
        for k, v in todo.items():
            f.write("%s\t%s\n" % (k, v.replace("\n", " ")))
    print("映射写回 %d 场；待画 %d 张（已有 %d 张）" % (len(d["scenes"]), len(todo), len(have)))
